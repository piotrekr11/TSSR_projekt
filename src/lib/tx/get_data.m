% =========================================================================
% Function name: get_data
% Author: Adam
% Creation date: 2026-11-10
% Last modified: 2026-11-11
%
% Description:
% This function provides ASCII art data depending on the payloads config
%
% Inputs:
%   config - configuration structure (here only payload_img selector is 
%   accessed)
%
% Outputs:
%   data - data structure containing: image in chars, size M, size N
%
% Notes:
%   Current version assumes static available payloads, but can be called
%   numerous times to construct a bigger payload data
% =========================================================================

function data = get_data(config)

    fprintf("    (f) get_data: started\n");

    % Validate input
    if ~isfield(config, 'payload_img')
        error("    (f) get_data: missing field 'payload_img'");
    end
    
    % New_line varoable to contain within image
    new_line = char(10);
    
    % Available ASCII payloads
    
    rabbit = [' (\_/)', new_line, ...
              ' (o.o)', new_line, ...
              ' (")_(")', new_line];
    
    owl = ['  ,_, ', new_line, ...
           ' (O,O)', new_line, ...
           ' (   )', new_line, ...
           '  " " ', new_line];
    
    cat = [' /\_/\ ', new_line, ...
           '( o.o )', new_line, ...
           ' > ^ < ', new_line];
    
    dog = [' / \__      ', new_line, ...
           '(    @\___  ', new_line, ...
           ' /         O', new_line, ...
           '/   (_____/ ', new_line, ...
           '/_____/   U ', new_line];
    
    fish = ['      /`·.¸       ', new_line, ...
            '     /¸...¸`:·    ', new_line, ...
            ' ¸.·´  ¸   `·.¸   ', new_line, ...
            ': © ):´;      ¸  }', new_line, ...
            ' `·.¸ `·  ¸.·´    ', new_line, ...
            '     `\\´´        ', new_line];

    castle = [ ...
    '                              |>>>                  ', new_line, ...
    '                              |                     ', new_line, ...
    '                  |>>>      _|_      |>>>           ', new_line, ...
    '                  |        /   \     |              ', new_line, ...
    '              _  _|_  _   /     \ _ _|_  _          ', new_line, ...
    '             |;|_|;|_|;| |       ||;|_|;|_|;|       ', new_line, ...
    '             \\.    .  / |       | \\.    .  /      ', new_line, ...
    '              \\:  .  /  |_______|  \\:  .  /       ', new_line, ...
    '               ||:   |  /         \  ||:   |        ', new_line, ...
    '               ||:.  | /           \ ||:.  |        ', new_line, ...
    '               ||:  _|/_____________\||:  _|        ', new_line, ...
    '               ||: |                  ||: |         ', new_line, ...
    '               ||: |     ______      ||: |          ', new_line, ...
    '               ||: |    |      |     ||: |          ', new_line, ...
    '               ||: |    |  []  |     ||: |          ', new_line, ...
    '               ||: |    |______|     ||: |          ', new_line, ...
    '              _||:_|_________________||:_|_         ', new_line, ...
    '             /                             \        ', new_line, ...
    '            /_______________________________\       ', new_line, ...
    '           /_________________________________\      ', new_line, ...
    '                  |               |                 ', new_line, ...
    '                  |      _____    |                 ', new_line, ...
    '                  |     |     |   |                 ', new_line, ...
    '                  |_____|     |___|                 ', new_line ...
    ];
    
    % choose the available image based on confiuration variable
    switch lower(config.payload_img)
        case "rabbit"
            data.image = rabbit;
        case "owl"
            data.image = owl;
        case "cat"
            data.image = cat;
        case "dog"
            data.image = dog;
        case "fish"
            data.image = fish;
        case "castle"
            data.image = castle;
        case "random"
            payloads = {rabbit, owl, cat, dog, fish};
            data.image = payloads{randi(numel(payloads))};
        otherwise
            error('    Unknown payload: %s', config.payload_img);
    end
    
    fprintf("    (f) get_data: selected image: %s\n", config.payload_img);
    
    % split lines and remove the last line
    lines = splitlines(string(data.image));
    lines(lines == "") = [];
    
    % calculate the size MxN
    data.size_m = numel(lines);
    data.size_n = max(strlength(lines));
    
    fprintf("    (f) get_data: image size: M=%d, N=%d\n", data.size_m, data.size_n);
    fprintf("    (f) get_data: finished successfully\n");

end